class Art {
  constructor(id, styleIds, title, artist, year, medium, description, imageUrl) {
    this.id = id;
    this.styleIds = styleIds;
    this.title = title;
    this.artist = artist;
    this.year = year;
    this.medium = medium;
    this.description = description;
    this.imageUrl = imageUrl;
  }
}
export default Art;
